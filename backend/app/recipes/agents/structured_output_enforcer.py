    def _strip_markdown_blocks(self, text: str) -> str:
        """Strips markdown code fences (```json ... ``` or ``` ... ```)."""
        if not text:
            return ""
        t = text.strip()
        # Regex to strip ```json ... ``` or ``` ... ```
        m = re.search(r"```(?:json)?\s*([\s\S]*?)\s*```", t, re.IGNORECASE)
        if m:
            return m.group(1).strip()
        # Find first { or [ and last } or ]
        first_brace = t.find("{")
        first_bracket = t.find("[")
        start_idx = -1
        if first_brace != -1 and (first_bracket == -1 or first_brace < first_bracket):
            start_idx = first_brace
            end_idx = t.rfind("}")
            if end_idx != -1 and end_idx >= start_idx:
                return t[start_idx : end_idx + 1].strip()
        elif first_bracket != -1:
            start_idx = first_bracket
            end_idx = t.rfind("]")
            if end_idx != -1 and end_idx >= start_idx:
                return t[start_idx : end_idx + 1].strip()
        return t

    def _repair_json_string(self, text: str) -> str:
        """Applies heuristic repairs for common LLM JSON syntax errors."""
        cleaned = self._strip_markdown_blocks(text)
        if not cleaned:
            return "{}"

        # Replace python literals
        cleaned = re.sub(r"\bTrue\b", "true", cleaned)
        cleaned = re.sub(r"\bFalse\b", "false", cleaned)
        cleaned = re.sub(r"\bNone\b", "null", cleaned)

        # Replace single-quoted keys with double quotes: 'key': -> "key":
        cleaned = re.sub(r"'(?P<k>[a-zA-Z0-9_\-]+)'\s*:", r'"\g<k>":', cleaned)
        # Replace single-quoted string values: : 'val' -> : "val"
        cleaned = re.sub(r":\s*'(?P<v>[^'\n]*)'", r': "\g<v>"', cleaned)

        # Remove trailing commas before closing braces/brackets
        cleaned = re.sub(r",\s*([\}\]])", r"\1", cleaned)

        # Balance missing closing braces
        open_braces = cleaned.count("{") - cleaned.count("}")
        if open_braces > 0:
            cleaned += "}" * open_braces
        open_brackets = cleaned.count("[") - cleaned.count("]")
        if open_brackets > 0:
            cleaned += "]" * open_brackets

        return cleaned

    def _regex_fallback_extract(self, text: str, properties: Dict[str, Any]) -> Dict[str, Any]:
        """Recovers field values using targeted regex patterns when JSON parsing fails."""
        recovered = {}
        for prop, prop_spec in properties.items():
            expected_type = prop_spec.get("type", "string")
            # First try quoted value: prop: "value" or 'value'
            quoted_match = re.search(rf'["\']?{re.escape(prop)}["\']?\s*[:=]\s*["\']([^"\']+)["\']', text, re.IGNORECASE)
            if quoted_match:
                raw_val = quoted_match.group(1).strip()
            else:
                # Unquoted: match word or number token until comma, space, or newline
                unquoted_match = re.search(rf'["\']?{re.escape(prop)}["\']?\s*[:=]\s*([a-zA-Z0-9_\-\.\$]+)', text, re.IGNORECASE)
                raw_val = unquoted_match.group(1).strip() if unquoted_match else ""

            if raw_val:
                if expected_type in ["number", "integer"]:
                    try:
                        recovered[prop] = float(raw_val) if expected_type == "number" else int(raw_val)
                    except ValueError:
                        recovered[prop] = prop_spec.get("default", None)
                elif expected_type == "boolean":
                    recovered[prop] = raw_val.lower() in ["true", "1", "yes"]
                else:
                    recovered[prop] = raw_val
            else:
                recovered[prop] = prop_spec.get("default", None)
        return recovered

    def execute(self, inputs: Dict[str, Any], config: Dict[str, Any], context: Optional[Dict[str, Any]] = None) -> Dict[str, Any]:
        df = inputs.get("dataframe") if "dataframe" in inputs else inputs.get("input")
        if df is None:
            df = inputs.get("df")
        if df is None:
            raise ValidationException("StructuredOutputEnforcer requires a valid tabular dataset on 'input'.")

        source_col = config.get("source_column", "llm_output")
        expected_schema = config.get("expected_schema") or {}
        extraction_mode = config.get("extraction_mode", "keep_both")
        auto_repair = config.get("auto_repair", True)
        handle_malformed = config.get("handle_malformed", "regex_extraction")
        audit_cols = config.get("audit_columns", True)

        # Extract schema properties and required fields
        properties = expected_schema.get("properties", {})
        required_fields = expected_schema.get("required", [])

        # Validate source column
        if source_col not in df.columns:
            # Fallback to any string/text column
            candidates = [c for c in df.columns if pd.api.types.is_string_dtype(df[c]) or df[c].dtype == "object"]
            if candidates:
                source_col = candidates[0]
                logger.info(f"Source column not found. Defaulting to candidate '{source_col}'.")
            else:
                raise ValidationException(f"Target LLM output column '{source_col}' not found in input table.")

        result_df = df.copy()

        # Handle empty dataframe edge case
        if len(result_df) == 0:
            if extraction_mode in ["unpack_columns", "keep_both"]:
                for prop in properties.keys():
                    result_df[prop] = pd.Series(dtype=object)
            if extraction_mode in ["clean_json_string", "keep_both"]:
                result_df["clean_json"] = pd.Series(dtype=object)
            if audit_cols:
                result_df["is_valid_json"] = pd.Series(dtype=bool)
                result_df["schema_valid"] = pd.Series(dtype=bool)
                result_df["parsing_error"] = pd.Series(dtype=object)
            return {"dataframe": result_df}

        parsed_records = []
        clean_json_strings = []
        is_valid_list = []
        schema_valid_list = []
        error_list = []

        for idx, row in result_df.iterrows():
            raw_text = str(row[source_col]) if pd.notna(row[source_col]) else ""
            parsed_dict = None
            is_valid = False
            schema_valid = False
            err_msg = ""

            candidate_text = self._repair_json_string(raw_text) if auto_repair else raw_text.strip()

            try:
                parsed_val = json.loads(candidate_text)
                if isinstance(parsed_val, dict):
                    parsed_dict = parsed_val
                    is_valid = True
                elif isinstance(parsed_val, list) and len(parsed_val) > 0 and isinstance(parsed_val[0], dict):
                    parsed_dict = parsed_val[0]
                    is_valid = True
                else:
                    err_msg = "Root JSON is not an object or object list"
            except Exception as ex:
                err_msg = f"JSONDecodeError: {str(ex)}"

            # Malformed recovery
            if not is_valid:
                if handle_malformed == "raise_error":
                    raise ValidationException(f"Failed to parse LLM structured output on row {idx}: {err_msg}")
                elif handle_malformed == "regex_extraction":
                    parsed_dict = self._regex_fallback_extract(raw_text, properties)
                else:  # fallback_defaults
                    parsed_dict = {k: v.get("default", None) for k, v in properties.items()}

            # Validate schema compliance
            if parsed_dict is not None:
                missing_reqs = [rf for rf in required_fields if rf not in parsed_dict or parsed_dict[rf] is None]
                if not missing_reqs:
                    schema_valid = True
                else:
                    schema_valid = False
                    if not err_msg:
                        err_msg = f"Missing required fields: {', '.join(missing_reqs)}"

                # Fill default values for missing property keys
                for p_name, p_spec in properties.items():
                    if p_name not in parsed_dict or parsed_dict[p_name] is None:
                        parsed_dict[p_name] = p_spec.get("default", None)
            else:
                parsed_dict = {k: v.get("default", None) for k, v in properties.items()}

            clean_json_strings.append(json.dumps(parsed_dict))
            parsed_records.append(parsed_dict)
            is_valid_list.append(is_valid)
            schema_valid_list.append(schema_valid)
            error_list.append(err_msg if err_msg else "")

        # Augment dataframe based on extraction mode
        if extraction_mode in ["unpack_columns", "keep_both"]:
            # If properties were provided, unpack those explicitly; otherwise unpack all discovered keys
            keys_to_unpack = list(properties.keys()) if properties else sorted({k for d in parsed_records for k in d.keys()})
            for k in keys_to_unpack:
                result_df[k] = [d.get(k, None) for d in parsed_records]

        if extraction_mode in ["clean_json_string", "keep_both"]:
            result_df["clean_json"] = clean_json_strings

        if audit_cols:
            result_df["is_valid_json"] = is_valid_list
            result_df["schema_valid"] = schema_valid_list
            result_df["parsing_error"] = error_list

        valid_count = sum(is_valid_list)
        schema_valid_count = sum(schema_valid_list)

        return {
            "dataframe": result_df,
            "metrics": {
                "total_rows_processed": len(result_df),
                "valid_json_count": valid_count,
                "valid_json_pct": round(valid_count / len(result_df) * 100, 2),
                "schema_compliant_count": schema_valid_count,
                "schema_compliant_pct": round(schema_valid_count / len(result_df) * 100, 2),
                "auto_repair_enabled": auto_repair
            }
        }

    def infer_output_schema(self, input_schemas: Dict[str, Any], config: Dict[str, Any]) -> Dict[str, Any]:
        schema = dict(input_schemas.get("input", {}))
        expected_schema = config.get("expected_schema") or {}
        properties = expected_schema.get("properties", {})
        extraction_mode = config.get("extraction_mode", "keep_both")
        audit_cols = config.get("audit_columns", True)

        if extraction_mode in ["unpack_columns", "keep_both"]:
            for prop, p_spec in properties.items():
                p_type = p_spec.get("type", "string")
                schema[prop] = p_type

        if extraction_mode in ["clean_json_string", "keep_both"]:
            schema["clean_json"] = "string"

        if audit_cols:
            schema["is_valid_json"] = "boolean"
            schema["schema_valid"] = "boolean"
            schema["parsing_error"] = "string"

        return schema
